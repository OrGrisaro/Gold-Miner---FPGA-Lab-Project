// pipeline (ff) to get the pixel color from the array 	 

always_ff@(posedge clk or negedge resetN)
begin
	if(!resetN) begin
		drawingRequest <=	1'b0;
	end
	else begin
		drawingRequest <=	1'b0;
		if (InsideRectangle == 1'b1 ) begin
			case(type_select)
			
				// digits
				2'b00: begin
					if(offsetX < 16 && offsetY < 32)
						drawingRequest <= (number_bitmap[digit][offsetY][offsetX]);
				end
				
				//level
				2'b01: begin
					if(offsetX < 80 && offsetY < 32)
						drawingRequest <= (level_bitmap[offsetY][offsetX]);
				end
				
				// win message
				2'b10: begin
					if(offsetX < 144 && offsetY < 32)
						drawingRequest <= (message_bitmap[0][offsetY][offsetX]);
				end
				
				// lose message
				2'b11: begin
					if(offsetX < 144 && offsetY < 32)
						drawingRequest <= (message_bitmap[1][offsetY][offsetX]);
				end
			endcase 
		end
	end 
end

